#!/usr/bin/env python3
"""Convert Android string resources to Compose Multiplatform resources.

Reads every app/src/main/res/values/*.xml that declares <string> or <plurals>
(colors.xml and themes.xml declare none and are skipped) and writes
shared/src/commonMain/composeResources/values/strings.xml with the same names,
in source order.

Text is copied verbatim: Compose Multiplatform uses the Android escape rules
(\\' \\" \\n \\\\ \\uXXXX, &amp; &lt;) and the same %1$s / %1$d / %% format
placeholders, so no rewriting is needed. Duplicate names, unsupported elements
(string-array, items other than one/other plurals) and a non-matching output
all fail loudly.

Usage: python3 tools/convert_strings.py [--check]
  --check  exit 1 if the committed output differs from a fresh conversion.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "app/src/main/res/values"
OUT = ROOT / "shared/src/commonMain/composeResources/values/strings.xml"
SOURCES = ["strings.xml", "feedback_audio.xml", "feedback_planning.xml", "feedback_targets.xml"]
QUANTITIES = {"zero", "one", "two", "few", "many", "other"}


def text_of(el):
    if len(el):
        raise SystemExit(f"{el.get('name')}: nested markup is not supported")
    return el.text or ""


def convert():
    names, lines = set(), []
    for fname in SOURCES:
        root = ET.parse(SRC_DIR / fname).getroot()
        for el in root:
            if not isinstance(el.tag, str):
                continue
            name = el.get("name")
            if el.tag == "string":
                if name in names:
                    raise SystemExit(f"duplicate resource name: {name}")
                names.add(name)
                lines.append(f'    <string name="{name}">{escape(text_of(el))}</string>')
            elif el.tag == "plurals":
                if name in names:
                    raise SystemExit(f"duplicate resource name: {name}")
                names.add(name)
                items = []
                for item in el:
                    q = item.get("quantity")
                    if item.tag != "item" or q not in QUANTITIES:
                        raise SystemExit(f"{name}: unsupported plural item")
                    items.append(f'        <item quantity="{q}">{escape(text_of(item))}</item>')
                lines.append(f'    <plurals name="{name}">\n' + "\n".join(items) + "\n    </plurals>")
            else:
                raise SystemExit(f"{fname}: unsupported element <{el.tag}> ({name})")
    header = ("<!-- Generated by tools/convert_strings.py from app/src/main/res/values/*.xml. "
              "Do not edit by hand. -->\n")
    return '<?xml version="1.0" encoding="utf-8"?>\n' + header + "<resources>\n" + "\n".join(lines) + "\n</resources>\n", len(names)


def main():
    text, count = convert()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("shared strings.xml is out of date; run tools/convert_strings.py", file=sys.stderr)
            return 1
        print(f"strings up to date ({count} resources)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({count} resources)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
